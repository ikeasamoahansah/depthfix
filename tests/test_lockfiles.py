import json
import tempfile
import unittest
from pathlib import Path

from depthfix import lockfiles


def _tmp(name, text):
    path = Path(tempfile.mkdtemp(prefix="depthfix-lock-")) / name
    path.write_text(text, encoding="utf-8")
    return path


class NpmLockTests(unittest.TestCase):
    def test_v3_layout(self):
        path = _tmp("package-lock.json", json.dumps({
            "lockfileVersion": 3,
            "packages": {
                "": {"name": "root", "version": "1.0.0"},   # the project itself
                "node_modules/node-sass": {"version": "7.0.3"},
                "node_modules/a/node_modules/chalk": {"version": "5.0.0"},
                "node_modules/@scope/pkg": {"version": "1.2.3"},
            }}))
        self.assertEqual(lockfiles.npm(path), {
            "node-sass": "7.0.3", "chalk": "5.0.0", "@scope/pkg": "1.2.3"})

    def test_v1_layout(self):
        path = _tmp("package-lock.json", json.dumps({
            "lockfileVersion": 1,
            "dependencies": {
                "axios": {"version": "0.19.0"},
                "chalk": {"version": "2.0.0", "requires": True,
                          "dependencies": {
                              "ansi-styles": {"version": "3.2.0"}}},
            }}))
        self.assertEqual(lockfiles.npm(path), {
            "axios": "0.19.0", "chalk": "2.0.0", "ansi-styles": "3.2.0"})

    def test_shrinkwrap_is_picked_up_by_load(self):
        directory = Path(tempfile.mkdtemp(prefix="depthfix-lock-"))
        (directory / "npm-shrinkwrap.json").write_text(
            json.dumps({"packages": {"node_modules/left-pad": {"version": "1.3.0"}}}))
        self.assertEqual(lockfiles.load(directory), {"left-pad": "1.3.0"})

    def test_garbage_yields_empty(self):
        path = _tmp("package-lock.json", "not json at all")
        self.assertEqual(lockfiles.npm(path), {})


class YarnLockTests(unittest.TestCase):
    def test_classic(self):
        path = _tmp("yarn.lock", """\
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY
# yarn lockfile v1

"@babel/core@^7.0.0", "@babel/core@7":
  version "7.26.10"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.26.10.tgz#abc"
  integrity sha512-xyz

left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#abc"

peer.js@^2:
  version "2.0.0"
""")
        self.assertEqual(lockfiles.yarn(path), {
            "@babel/core": "7.26.10", "left-pad": "1.3.0", "peer.js": "2.0.0"})

    def test_berry_style(self):
        path = _tmp("yarn.lock", """\
# This file is generated by running "yarn install" inside your project.

"left-pad@npm:^1.3.0":
  version: 1.3.0

"@babel/core@npm:^7.0.0":
  version: 7.26.10
""")
        self.assertEqual(lockfiles.yarn(path),
                         {"left-pad": "1.3.0", "@babel/core": "7.26.10"})


class PnpmLockTests(unittest.TestCase):
    def test_v6_packages_section(self):
        path = _tmp("pnpm-lock.yaml", """\
lockfileVersion: '6.0'

dependencies:

  node-sass:
    specifier: ^7.0.3
    version: 7.0.3

packages:

  /node-sass@7.0.3:
    resolution: {integrity: sha512-aaa}

  '@scope/pkg@1.2.3':
    resolution: {integrity: sha512-bbb}

  left-pad@1.3.0(peer@2.0.0)(sha512-abc):
    resolution: {integrity: sha512-ccc}

  tarball@https://example.com/x.tgz:
    resolution: {integrity: sha512-ddd}
""")
        self.assertEqual(lockfiles.pnpm(path), {
            "node-sass": "7.0.3", "@scope/pkg": "1.2.3", "left-pad": "1.3.0"})


if __name__ == "__main__":
    unittest.main()
